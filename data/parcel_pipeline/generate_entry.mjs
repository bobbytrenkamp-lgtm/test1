/* data/parcel_pipeline/generate_entry.mjs
 *
 *   node data/parcel_pipeline/generate_entry.mjs --fips <fips> [--fields "A,B,C"]
 *
 * Given a catalog record (status: candidate/thin/requires-review — NOT yet
 * production) and a real source field list, runs field_mapper.mjs and
 * writes a draft registry.js-shaped entry to
 * data/parcel_pipeline/drafts/<fips>.js for a human to review, verify
 * against a live sample record, and hand-paste into js/parcel/registry.js
 * themselves.
 *
 * THIS SCRIPT NEVER WRITES TO js/parcel/registry.js AND NEVER CHANGES A
 * CATALOG RECORD'S status. Promotion to production remains a human act —
 * landing the actual registry.js PR — consistent with this pipeline's
 * "never auto-merge, never auto-publish uncertain data" rule. If the field
 * mapper leaves anything in requiresReview, the draft is still written, but
 * clearly marked incomplete, with the open questions listed for a human to
 * resolve before it's usable.
 *
 * --fields is optional: if omitted, the source field list is read from the
 * catalog record's own `available_fields` (already populated for every
 * hand-transcribed candidate this session, e.g. Mecklenburg NC, Jackson
 * MO). Pass --fields to override with fresher data from a live re-probe.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadSchemaFieldIds, loadRequiredSchemaFieldIds } from './lib/load_registry.mjs';
import { mapFields } from './field_mapper.mjs';
import { validateMapping } from './validate_field_mapping.mjs';

const CATALOG_PATH = join(ROOT, 'data/parcel_source_catalog.json');
const SYNONYMS_PATH = join(ROOT, 'data/parcel_field_synonyms.json');
const DRAFTS_DIR = join(ROOT, 'data/parcel_pipeline/drafts');

function parseArgs(argv) {
  const args = { fips: null, fields: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--fips') args.fips = argv[++i];
    else if (argv[i] === '--fields') args.fields = argv[++i];
  }
  return args;
}

function jsStringLiteral(value) {
  return value == null ? 'null' : `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

// 8/6-space indentation here matches js/parcel/registry.js's own real
// entries exactly (confirmed against e.g. Jefferson County AL's fieldMap/
// notProvidedBySource block) so a promote_batch.mjs-inserted entry needs no
// further re-indentation beyond buildEntryBody's key line.
function formatFieldMap(fieldMap) {
  const lines = Object.entries(fieldMap).map(([k, v]) => `        ${k}: ${jsStringLiteral(v)},`);
  return lines.join('\n');
}

function formatNotProvided(list) {
  if (!list.length) return '      ]';
  const lines = [];
  for (let i = 0; i < list.length; i += 4) {
    lines.push('        ' + list.slice(i, i + 4).map(jsStringLiteral).join(', ') + ',');
  }
  return lines.join('\n') + '\n      ]';
}

function inferConnector(sourceType) {
  if (!sourceType) return 'arcgis';
  if (sourceType.startsWith('arcgis')) return 'arcgis';
  if (sourceType === 'geojson') return 'geojson';
  if (sourceType === 'wfs') return 'wfs';
  return 'arcgis'; // best-effort default; flagged in the draft's header for human confirmation
}

export function buildDraft(catalogRecord, mapperResult, validation) {
  const connector = inferConnector(catalogRecord.source_type);
  const whereClause = catalogRecord.county_filter_field && catalogRecord.county_filter_value
    ? `\n      where:       "${catalogRecord.county_filter_field} = '${catalogRecord.county_filter_value}'",`
    : '';

  const reviewSection = mapperResult.requiresReview.length
    ? '\n\n/* ═══ NEEDS HUMAN REVIEW BEFORE THIS ENTRY IS USABLE ═══\n' +
      mapperResult.requiresReview.map(r => {
        const label = r.canonicalId || r.sourceField;
        const candidates = r.candidates ? ` Candidates: ${r.candidates.join(', ')}.` : '';
        return ` * ${label} (${r.reason}):${candidates} ${r.note || ''}`.trim();
      }).join('\n') +
      '\n * Resolve each item above (add to fieldMap or notProvidedBySource by hand), ' +
      're-run data/parcel_pipeline/validate_field_mapping.mjs against the result, then ' +
      'copy this entry into js/parcel/registry.js and confirm against a live sample record.\n */'
    : '';

  return `/* DRAFT — generated by data/parcel_pipeline/generate_entry.mjs, NOT auto-committed.
 * Source: catalog record for FIPS ${catalogRecord.fips} (${catalogRecord.name}), status "${catalogRecord.status}".
 * Connector inferred from catalog source_type "${catalogRecord.source_type || 'unknown'}" — confirm before use.
 * Mapping validation: ${validation.ok
   ? 'PASS (30/30 canonical fields covered, zero gaps/overlap).'
   : validation.requiredMissing.length
     ? `NON-FUNCTIONAL — required field(s) not mapped: ${validation.requiredMissing.join(', ')}. ` +
       'schema.js rejects any record missing these; this draft cannot be used as-is.'
     : 'INCOMPLETE — see review section below.'}
 * This is NOT verified against a live sample record. Before pasting into js/parcel/registry.js:
 *   1. Resolve every item in the review section below, if any.
 *   2. Re-fetch the service and confirm these field names still exist.
 *   3. Pull one real sample record and sanity-check the mapped values.
 *   4. Run node tests/parcel.test.js and the catalog validator.
 */
${buildEntryBody(catalogRecord, mapperResult)}${reviewSection}
`;
}

/* Pure. Formats just the registry.js-shaped entry body (the `'fips': {...},`
   block, no surrounding DRAFT comment or review section) -- the exact text
   both buildDraft() (wrapped with the human-facing draft header above) and
   promote_batch.mjs (inserted directly into js/parcel/registry.js once a
   candidate has cleared every promotion gate, including zero remaining
   requiresReview items) need. Kept as one shared function so the two never
   drift into producing subtly different entry shapes. */
export function buildEntryBody(catalogRecord, mapperResult, attributionNote = 'DRAFT entry, not yet verified against a live sample record.') {
  const connector = inferConnector(catalogRecord.source_type);
  const whereClause = catalogRecord.county_filter_field && catalogRecord.county_filter_value
    ? `\n      where:       "${catalogRecord.county_filter_field} = '${catalogRecord.county_filter_value}'",`
    : '';

  return `'${catalogRecord.fips}': {
      id:          ${jsStringLiteral(catalogRecord.id || `TODO-${catalogRecord.fips}`)},
      name:        ${jsStringLiteral(catalogRecord.name)},
      state:       ${jsStringLiteral(catalogRecord.state)},
      fips:        ${jsStringLiteral(catalogRecord.fips)},
      connector:   ${jsStringLiteral(connector)},
      serviceUrl:  ${jsStringLiteral(catalogRecord.service_url)},${whereClause}

      minZoom:     14,
      maxFeatures: 500,

      fieldMap: {
${formatFieldMap(mapperResult.fieldMap)}
      },

      notProvidedBySource: [
${formatNotProvided(mapperResult.notProvidedBySource)},

      outFields: null,

      attribution: {
        name:    ${jsStringLiteral(catalogRecord.official_publisher)},
        url:     ${jsStringLiteral(catalogRecord.portal_url)},
        portal:  ${jsStringLiteral(catalogRecord.service_url)},
        license: ${jsStringLiteral(catalogRecord.licensing_notes || 'Public government data. Verify terms before commercial redistribution.')},
        note:    ${jsStringLiteral(attributionNote)},
      },
    },`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.fips) {
    console.error('Usage: node generate_entry.mjs --fips <fips> [--fields "A,B,C"]');
    process.exit(2);
  }

  const catalog = JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));
  const record = catalog.jurisdictions[args.fips];
  if (!record) {
    console.error(`FIPS ${args.fips} not found in ${CATALOG_PATH}`);
    process.exit(1);
  }
  if (record.status === 'production') {
    console.error(`FIPS ${args.fips} is already status=production — nothing to generate.`);
    process.exit(1);
  }

  const sourceFields = args.fields
    ? args.fields.split(',').map(s => s.trim()).filter(Boolean)
    : record.available_fields || [];
  if (sourceFields.length === 0) {
    console.error(`No source fields available for FIPS ${args.fips} (catalog has no available_fields ` +
      `and --fields was not passed).`);
    process.exit(1);
  }

  const synonyms = JSON.parse(readFileSync(SYNONYMS_PATH, 'utf8')).synonyms;
  const canonicalFieldIds = loadSchemaFieldIds();
  const requiredFieldIds = loadRequiredSchemaFieldIds();

  const mapperResult = mapFields(sourceFields, canonicalFieldIds, synonyms);
  const validation = validateMapping(
    mapperResult.fieldMap, mapperResult.notProvidedBySource, canonicalFieldIds, requiredFieldIds
  );

  const draft = buildDraft(record, mapperResult, validation);

  mkdirSync(DRAFTS_DIR, { recursive: true });
  const outPath = join(DRAFTS_DIR, `${args.fips}.js`);
  writeFileSync(outPath, draft);

  console.log(`Draft written to ${outPath}`);
  console.log(`  Source fields: ${sourceFields.length}`);
  console.log(`  Mapped: ${Object.keys(mapperResult.fieldMap).length - 1} (+county_fips)`);
  console.log(`  notProvidedBySource: ${mapperResult.notProvidedBySource.length}`);
  console.log(`  Needs review: ${mapperResult.requiresReview.length}`);
  console.log(`  Validation: ${validation.ok ? 'PASS' : 'INCOMPLETE — see draft file for open items'}`);
  if (validation.requiredMissing.length) {
    console.log(`  ⚠ REQUIRED field(s) not mapped — this draft is non-functional as-is: ` +
      validation.requiredMissing.join(', '));
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
